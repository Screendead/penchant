#!/usr/bin/env python3
"""Writes lib/insights/zone_locations.dart from the system's zone.tab.

Each time zone's representative city, rounded to whole degrees: Daylight's
rough location when no place is known. Run from the repo root:
  python3 tools/zone-locations.py [/usr/share/zoneinfo/zone.tab]
"""
import re
import sys

source = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/zoneinfo/zone.tab"


def degrees(text, width):
    sign = -1 if text[0] == "-" else 1
    d = int(text[1 : 1 + width])
    m = int(text[1 + width : 3 + width])
    s = int(text[3 + width : 5 + width] or 0)
    return sign * round(d + m / 60 + s / 3600)


zones = {}
for line in open(source, encoding="utf-8"):
    if line.startswith("#") or not line.strip():
        continue
    fields = line.rstrip("\n").split("\t")
    match = re.fullmatch(r"([+-]\d+)([+-]\d+)", fields[1])
    lat, lon = match.group(1), match.group(2)
    zones[fields[2]] = (degrees(lat, 2), degrees(lon, 3))

out = [
    "// Generated by tools/zone-locations.py from zone.tab; do not edit.",
    "",
    "/// Each time zone's representative city, in whole degrees north and east.",
    "const Map<String, (int, int)> zoneLocations = <String, (int, int)>{",
]
for name in sorted(zones):
    lat, lon = zones[name]
    out.append(f"  '{name}': ({lat}, {lon}),")
out.append("};")
open("lib/insights/zone_locations.dart", "w", encoding="utf-8").write("\n".join(out) + "\n")
print(len(zones), "zones")
